"""Section renderer for static sites (Story 17.2). No LLM.

When every section of a static FrontendSpec is in the section library (`templates/nextjs_overlay/files/renderer`),
the frontend is data plus thin route files and `generate_frontend` makes no engine call:

    src/content/site.json                pages → section trees (content, bound collection), content collections
    src/components/renderer/registry.ts  component name → library component, for the sections this site uses
    src/components/sections/types.ts     the section content types, from the props models (Story 17.1)
    src/app/<route>/page.tsx             metadata + <PageRenderer pageId=… />

Anything else (dynamic mode, forms, custom components, route parameters, the sidebar shell) still goes to the
engine; the plan says why in `rendererGaps`.
"""

import json
from typing import Any

from src.modules.shared.domain.backend_spec.naming import to_pascal
from src.modules.shared.domain.frontend_spec import BUILTIN_SECTIONS, LAYOUT_SECTIONS, iter_sections
from src.modules.shared.domain.frontend_spec.registry import section_props_schemas

HEADER = "// Generated by the Fullstack Generation Agent from the FrontendSpec. Do not edit.\n"
CONTENT_SECTIONS = frozenset(
    {"Hero", "Features", "CallToAction", "Testimonials", "Faq", "Pricing", "Stats", "Gallery", "RichText"}
    | {"ContactInfo"}
)
RECORD_SECTIONS = frozenset({"CardGrid", "List", "DataTable"})  # records of a content collection
RENDERED = CONTENT_SECTIONS | RECORD_SECTIONS | LAYOUT_SECTIONS
LIBRARY_DIR = "src/components/sections"
SITE_FILE = "src/content/site.json"
REGISTRY_FILE = "src/components/renderer/registry.ts"
TYPES_FILE = f"{LIBRARY_DIR}/types.ts"


def renderer_gaps(spec: dict[str, Any], routes: list[dict[str, Any]]) -> list[str]:
    """Why the section renderer cannot build this frontend (empty: it can)."""
    if spec["project"]["mode"] != "static":
        return ["dynamic mode: data sections are rendered from Story 17.4"]
    gaps = []
    if (spec.get("layout") or {}).get("shell") == "sidebar":
        gaps.append("layout.shell 'sidebar' is not in the section library")
    declared = {component["name"]: component.get("kind", "section") for component in spec.get("components", [])}
    for route in routes:
        if route["params"]:
            gaps.append(f"{route['pageId']}: route parameters ({route['route']})")
        for section in iter_sections(route["sections"]):
            where = f"{route['pageId']}/{section['id']}"
            name = section["component"]
            if name not in RENDERED or name not in BUILTIN_SECTIONS or declared.get(name, "section") != "section":
                gaps.append(f"{where}: {name} is not in the section library")
            elif section.get("form"):
                gaps.append(f"{where}: forms")
            elif name in RECORD_SECTIONS and (section.get("data") or {}).get("kind") != "content":
                gaps.append(f"{where}: {name} needs a content collection")
    return gaps


# -- generated files ---------------------------------------------------------------------------------------------------


def _site_section(section: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {"id": section["id"], "component": section["component"]}
    if section.get("content"):
        out["content"] = section["content"]
    data = section.get("data") or {}
    if data.get("kind") == "content":
        out["data"] = {"collection": data["collection"], **({"fields": data["fields"]} if data.get("fields") else {})}
    if section.get("children"):
        out["children"] = [_site_section(child) for child in section["children"]]
    return out


def site_json(plan: dict[str, Any], spec: dict[str, Any]) -> str:
    site = {
        "pages": {
            route["pageId"]: {"title": route["title"], "sections": [_site_section(s) for s in route["sections"]]}
            for route in plan["routes"]
        },
        "collections": {item["collection"]: item["records"] for item in spec.get("content", [])},
    }
    return json.dumps(site, indent=2, ensure_ascii=False) + "\n"


def used_sections(plan: dict[str, Any]) -> list[str]:
    return sorted({section["component"] for route in plan["routes"] for section in iter_sections(route["sections"])})


def registry_ts(plan: dict[str, Any]) -> str:
    names = used_sections(plan)
    imports = "".join(f'import {{ {name} }} from "@/components/sections/{name}";\n' for name in names)
    entries = "".join(f"  {name}: {name} as unknown as TSectionComponent,\n" for name in names)
    return (
        HEADER
        + 'import type { ComponentType, ReactNode } from "react";\n'
        + imports
        + "\nexport type TSectionComponent = ComponentType<Record<string, unknown> & { children?: ReactNode }>;\n\n"
        + "/** The built-in sections this site uses, by FrontendSpec component name. */\n"
        + f"export const sections: Record<string, TSectionComponent> = {{\n{entries}}};\n"
    )


def _ts_name(name: str) -> str:
    return f"T{name.removesuffix('Props')}Content" if name.endswith("Props") else f"T{name}"


def _ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _ts_name(schema["$ref"].rsplit("/", 1)[-1])
    if "anyOf" in schema:
        parts = [_ts(option) for option in schema["anyOf"] if option.get("type") != "null"]
        return " | ".join(dict.fromkeys(parts))
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        item = _ts(schema.get("items") or {})
        return f"({item})[]" if " | " in item else f"{item}[]"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}.get(
        kind, "Record<string, unknown>"
    )


def section_props_ts() -> str:
    """TypeScript for every section content model (Story 17.1): `T<Section>Content`, `T<Item>`, `TCta`."""
    blocks = []
    for name, schema in sorted(section_props_schemas().items()):
        required = set(schema.get("required") or [])
        fields = "".join(
            f"  {key}{'' if key in required else '?'}: {_ts(prop)};\n"
            for key, prop in (schema.get("properties") or {}).items()
        )
        blocks.append(f"export type {_ts_name(name)} = {{\n{fields}}};\n")
    return HEADER + "\n" + "\n".join(blocks)


def route_page(route: dict[str, Any]) -> str:
    seo = route.get("seo") or {}
    metadata = {"title": seo.get("title") or route["title"]}
    if seo.get("description"):
        metadata["description"] = seo["description"]
    return (
        HEADER
        + 'import type { Metadata } from "next";\n'
        + 'import { PageRenderer } from "@/components/renderer/PageRenderer";\n\n'
        + f"export const metadata: Metadata = {json.dumps(metadata, ensure_ascii=False)};\n\n"
        + f"export default function {to_pascal(route['pageId'].replace('-', '_'))}Page() {{\n"
        + f"  return <PageRenderer pageId={json.dumps(route['pageId'])} />;\n"
        + "}\n"
    )


def renderer_files(plan: dict[str, Any], spec: dict[str, Any]) -> dict[str, str]:
    files = {SITE_FILE: site_json(plan, spec), REGISTRY_FILE: registry_ts(plan), TYPES_FILE: section_props_ts()}
    for route in plan["routes"]:
        files[route["file"]] = route_page(route)
    return files


def library_files(plan: dict[str, Any], available: list[str]) -> list[str]:
    """The library files a site needs: its sections plus the shared helpers (every file that is not a section)."""
    used = set(used_sections(plan))
    keep = []
    for relative in available:
        if not relative.startswith(f"{LIBRARY_DIR}/"):
            keep.append(relative)
            continue
        stem = relative.rsplit("/", 1)[-1].split(".", 1)[0]
        if stem in used or stem not in BUILTIN_SECTIONS:
            keep.append(relative)
    return keep
