from .contract import contract_operations, resolve

LIBRARY_ROOT = Path(__file__).resolve().parents[2] / "templates" / "nextjs_overlay" / "files" / "renderer"
_UI_IMPORT = re.compile(r'from "@/components/ui/([a-z0-9-]+)"')
HEADER = "// Generated by the Fullstack Generation Agent from the FrontendSpec. Do not edit.\n"
CONTENT_SECTIONS = frozenset(
    {"Hero", "Features", "CallToAction", "Testimonials", "Faq", "Pricing", "Stats", "Gallery", "RichText"}
    | {"ContactInfo"}
)
RECORD_SECTIONS = frozenset({"CardGrid", "List", "DataTable"})  # records of a collection or a list operation
RENDERED = CONTENT_SECTIONS | RECORD_SECTIONS | LAYOUT_SECTIONS | {"DetailView", "Form"}
FORM_FIELD_TYPES = frozenset(
    {"string", "text", "email", "url", "tel", "password", "integer", "number", "decimal", "boolean", "date", "enum"}
)
LIBRARY_DIR = "src/components/sections"
SITE_FILE = "src/content/site.json"
