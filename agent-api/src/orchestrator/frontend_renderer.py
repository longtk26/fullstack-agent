"""Section renderer (Stories 17.2 static, 17.4 dynamic). No LLM.

When every section of a FrontendSpec is in the section library (`templates/nextjs_overlay/files/renderer`), the
frontend is data plus thin route files and `generate_frontend` makes no engine call:

    src/content/site.json                pages → section trees (content, data binding, columns, link, states),
                                         content collections, form definitions
    src/components/renderer/registry.ts  component name → library component, for the sections this site uses
    src/components/sections/types.ts     the section content types, from the props models (Story 17.1)
    src/components/renderer/bindings.ts  operationId → fetcher / query keys (frontend_codegen.bindings_ts)
    src/components/renderer/form-schemas.ts  form id → generated Zod schema and defaults
    src/app/<route>/page.tsx             metadata + <PageRenderer pageId=… />

Data sections read through the generated API client in dynamic mode (mocks first, then the live backend) and from
content collections in static mode. Anything else (custom components, static forms, the sidebar shell, route
parameters in static mode) still goes to the engine; the plan says why in `rendererGaps`.
"""

