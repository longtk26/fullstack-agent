def generated_files(plan: dict[str, Any], spec: dict[str, Any], contract: dict[str, Any] | None) -> dict[str, str]:
    """Every generator-owned file with its content (paths relative to the frontend project)."""
    files = {
        "src/app/globals.css": globals_css(plan["theme"]),
        "src/config/site.ts": site_ts(plan, spec),
        "src/lib/forms.ts": forms_ts(plan, contract),
        "tests/e2e/smoke.spec.ts": smoke_spec(plan, spec, contract),
        "tests/unit/forms.test.ts": forms_unit_test(plan),
    }
    forms = forms_spec(plan)
    if forms:
        files["tests/e2e/forms.spec.ts"] = forms
    for item in spec.get("content", []):
        files[f"src/content/{to_kebab(item['collection'])}.json"] = (
            json.dumps(item["records"], indent=2, ensure_ascii=False) + "\n"
        )
    if plan.get("rendering") == "renderer":
        files |= renderer_files(plan, spec)
    if contract is not None:
        files |= {
            "src/lib/api/types.ts": types_ts(contract),
            "src/lib/api/operations.ts": operations_ts(contract),
            "src/lib/api/query-keys.ts": query_keys_ts(contract),
            "src/lib/api/queries.ts": queries_ts(contract),
            "src/mocks/fixtures.json": json.dumps(
                (contract.get("x-bga") or {}).get("fixtures") or {}, indent=2, ensure_ascii=False
            )
            + "\n",
            "src/mocks/operations.json": json.dumps(mock_operations(contract), indent=2, ensure_ascii=False) + "\n",
            "tests/unit/api.test.ts": api_unit_test(contract),
        }
    return dict(sorted(files.items()))
