def forms_spec(plan: dict[str, Any]) -> str | None:
    cases = []
    by_id = {form["id"]: form for form in plan["forms"]}
    for test in plan["tests"]:
        if test["kind"] != "form":
            continue
        form = by_id[test["formId"]]
        fields = []
        skip = test.get("skip")
        for field in form["fields"]:
            if field.get("hidden") or field.get("value") is not None and str(field.get("value")).startswith("$"):
                continue
            if field.get("type") == "enum":
                if field.get("required"):
                    skip = skip or "required select fields are not filled automatically"
                continue
            if not field.get("required"):
                continue
            fields.append(
                {
                    "label": field.get("label") or field["name"],
                    "kind": "check" if field.get("type") == "boolean" else "fill",
                    "value": str(sample_value(field)),
                }
            )
        case = {
            "id": test["id"],
            "path": test["path"],
            "submit": form.get("submitLabel") or "Submit",
            "fields": fields,
            "toast": (form.get("onSuccess") or {}).get("toast"),
            "navigate": (form.get("onSuccess") or {}).get("navigate"),
        }
        if skip:
            case["skip"] = skip
        cases.append(case)
    if not cases:
        return None
    return (
        HEADER
        + 'import { expect, test } from "@playwright/test";\n\n'
        + "type TFormCase = {\n  id: string;\n  path: string | null;\n  submit: string;\n"
        + '  fields: { label: string; kind: "fill" | "check"; value: string }[];\n'
        + "  toast: string | null;\n  navigate: string | null;\n  skip?: string;\n};\n\n"
        + f"const forms: TFormCase[] = {json.dumps(cases, indent=2, ensure_ascii=False)};\n\n"
        + "for (const form of forms) {\n"
        + "  test(`${form.id} submits`, async ({ page }) => {\n"
        + '    test.skip(Boolean(form.skip) || form.path === null, form.skip ?? "");\n'
        + "    await page.goto(form.path as string);\n"
        + "    for (const field of form.fields) {\n"
        + "      const input = page.getByLabel(field.label, { exact: false }).first();\n"
        + '      if (field.kind === "check") await input.check();\n'
        + "      else await input.fill(field.value);\n"
        + "    }\n"
        + '    await page.getByRole("button", { name: form.submit }).click();\n'
        + "    if (form.toast) await expect(page.getByText(form.toast).first()).toBeVisible();\n"
        + "    else if (form.navigate) await expect(page).toHaveURL(new RegExp(form.navigate));\n"
        + "  });\n"
        + "}\n"
    )


