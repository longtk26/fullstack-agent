HEADER = "// Generated by the Fullstack Generation Agent from the FrontendSpec and the API contract. Do not edit.\n"
_PATH_PARAM = re.compile(r"\{([^}]+)\}")
_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def _prop(name: str) -> str:
    return name if _IDENT.match(name) else _json(name)


# -- types ---------------------------------------------------------------------------------------------------------


def type_name(schema_name: str) -> str:
    """`ProductResponse` → `TProduct`; `ListProductsResponse` → `TListProductsResponse`; `ErrorResponse` →
    `TApiErrorBody`; anything else → `T<name>`."""
    if schema_name == "ErrorResponse":
        return "TApiErrorBody"
    if schema_name.endswith("Response") and not schema_name.startswith("List"):
        return "T" + schema_name.removesuffix("Response")
    return "T" + schema_name


def ts_type(schema: Any, indent: str = "") -> str:
    if not isinstance(schema, dict) or not schema:
        return "unknown"
    if "$ref" in schema:
        return type_name(schema["$ref"].rsplit("/", 1)[-1])
    kinds = schema.get("type")
    kinds = kinds if isinstance(kinds, list) else [kinds] if kinds else []
    if "enum" in schema:
        literals = [_json(value) if value is not None else "null" for value in schema["enum"]]
        return " | ".join(literals)
    parts = []
    for kind in kinds:
        if kind == "string":
            parts.append("string")
        elif kind in ("integer", "number"):
            parts.append("number")
        elif kind == "boolean":
            parts.append("boolean")
        elif kind == "null":
            parts.append("null")
        elif kind == "array":
            parts.append(f"{_wrap(ts_type(schema.get('items', {}), indent))}[]")
        elif kind == "object":
            parts.append(_object(schema, indent))
    if not kinds and "properties" in schema:
        parts.append(_object(schema, indent))
    unique = list(dict.fromkeys(parts))
    return " | ".join(unique) if unique else "unknown"


def _wrap(text: str) -> str:
    return f"({text})" if "|" in text else text


def _object(schema: dict[str, Any], indent: str) -> str:
    properties = schema.get("properties") or {}
    if not properties:
        return "Record<string, unknown>"
    required = set(schema.get("required") or [])
    inner = indent + "  "
    lines = [
        f"{inner}{_prop(name)}{'' if name in required else '?'}: {ts_type(value, inner)};"
        for name, value in properties.items()
    ]
    return "{\n" + "\n".join(lines) + f"\n{indent}}}"


def _params(operation: dict[str, Any]) -> list[dict[str, Any]]:
    return [p for p in operation.get("parameters") or [] if p.get("in") in ("path", "query")]


def _params_type(function: str) -> str:
    return f"T{to_pascal(function)}Params"


def types_ts(contract: dict[str, Any]) -> str:
    schemas = contract.get("components", {}).get("schemas", {})
    blocks = [HEADER]
    for name in sorted(schemas):
        blocks.append(f"export type {type_name(name)} = {ts_type(schemas[name])};\n")
    for operation_id, found in sorted(contract_operations(contract).items()):
        params = _params(found["operation"])
        if not params:
            continue
        function = operation_function(operation_id, (found["operation"].get("x-bga") or {}).get("action"))
        lines = [
            f"  {_prop(p['name'])}{'' if p.get('required') else '?'}: {ts_type(p.get('schema', {}), '  ')};"
            for p in params
        ]
        blocks.append(f"export type {_params_type(function)} = {{\n" + "\n".join(lines) + "\n};\n")
    return "\n".join(blocks)


# -- operations, keys, hooks ---------------------------------------------------------------------------------------


def _response_type(operation: dict[str, Any]) -> str:
    for status, response in sorted((operation.get("responses") or {}).items()):
        if status.startswith("2"):
            schema = (response.get("content") or {}).get("application/json", {}).get("schema")
            return ts_type(schema) if schema else "void"
    return "void"


def _request_type(operation: dict[str, Any]) -> str | None:
    body = (operation.get("requestBody") or {}).get("content", {}).get("application/json")
    return ts_type(body.get("schema", {})) if body else None


class _Operation:
    def __init__(self, operation_id: str, found: dict[str, Any]):
        op = found["operation"]
        meta = op.get("x-bga") or {}
        self.id = operation_id
        self.method = found["method"]
        self.path = found["path"]
        self.action = meta.get("action")
        self.entity = meta.get("entity")
        self.function = operation_function(operation_id, self.action)
        self.keys = resource_keys(operation_id)
        self.params = _params(op)
        self.path_params = [p["name"] for p in self.params if p["in"] == "path"]
        self.query_params = [p["name"] for p in self.params if p["in"] == "query"]
        self.params_optional = not any(p.get("required") for p in self.params)
        self.response = _response_type(op)
        self.request = _request_type(op)
        self.raw = op

    @property
    def hook(self) -> str:
        return f"use{self.function[:1].upper()}{self.function[1:]}"

    def signature(self) -> list[str]:
        args = []
        if self.params:
            default = " = {}" if self.params_optional else ""
            args.append(f"params: {_params_type(self.function)}{default}")
        if self.request:
            args.append(f"body: {self.request}")
        return args

    def url(self) -> str:
        path = _PATH_PARAM.sub(lambda m: f"${{encodeURIComponent(String(params.{m.group(1)}))}}", self.path)
        return f"`{path}`" if self.path_params else _json(self.path)


def _ops(contract: dict[str, Any]) -> list[_Operation]:
    return [_Operation(operation_id, found) for operation_id, found in sorted(contract_operations(contract).items())]


def _type_imports(body: str, local: set[str] = frozenset()) -> str:
    """`import type { … } from "./types"` for exactly the T-types the body uses."""
    names = set(re.findall(r"\bT[A-Z][A-Za-z0-9]*", body)) - set(local)
    if not names:
        return ""
    return "import type {\n" + "".join(f"  {name},\n" for name in sorted(names)) + '} from "./types";\n'


def operations_ts(contract: dict[str, Any]) -> str:
    ops = _ops(contract)
    out: list[str] = []
    for op in ops:
        options = []
        if op.query_params:
            query = ", ".join(f"{_prop(name)}: params.{name}" for name in op.query_params)
            options.append(f"query: {{ {query} }}")
        if op.request:
            options.append("body")
        call_options = f", {{ {', '.join(options)} }}" if options else ""
        out.append(
            f"/** {op.method} {op.path} (`{op.id}`) */\n"
            f"export function {op.function}({', '.join(op.signature())}): Promise<{op.response}> {{\n"
            f'  return request<{op.response}>("{op.method}", {op.url()}{call_options});\n'
            "}\n"
        )
    body = "\n".join(out)
    return "\n".join([HEADER, 'import { request } from "./client";\n' + _type_imports(body), body])


def query_keys_ts(contract: dict[str, Any]) -> str:
    resources = sorted({op.keys: op.id.rsplit(".", 1)[0] for op in _ops(contract)}.items())
    out = [HEADER]
    for keys, resource in resources:
        out.append(
            f"export const {keys} = {{\n"
            f"  all: [{_json(resource)}] as const,\n"
            f'  list: (params: object = {{}}) => [...{keys}.all, "list", params] as const,\n'
            f'  detail: (params: object = {{}}) => [...{keys}.all, "detail", params] as const,\n'
            "};\n"
        )
    return "\n".join(out)


def queries_ts(contract: dict[str, Any]) -> str:
    ops = _ops(contract)
    out = ["type TQueryOptions = { enabled?: boolean };\n"]
    for op in ops:
        if op.method == "GET":
            kind = "list" if op.action == "list" else "detail"
            params_arg = op.signature()[0] if op.params else None
            args = ", ".join([*([params_arg] if params_arg else []), "options: TQueryOptions = {}"])
            call = "params" if op.params else ""
            out.append(
                f"export function {op.hook}({args}) {{\n"
                "  return useQuery({\n"
                f"    queryKey: {op.keys}.{kind}({call}),\n"
                f"    queryFn: () => {op.function}({call}),\n"
                "    enabled: options.enabled ?? true,\n"
                "  });\n}\n"
            )
            continue
        if op.params and op.request:
            variables = f"{{ params: {_params_type(op.function)}; body: {op.request} }}"
            fn = f"({{ params, body }}: {variables}) => {op.function}(params, body)"
        elif op.params:
            fn = f"(params: {_params_type(op.function)}) => {op.function}(params)"
        elif op.request:
            fn = f"(body: {op.request}) => {op.function}(body)"
        else:
            fn = f"() => {op.function}()"
        out.append(
            f"export function {op.hook}() {{\n"
            "  const queryClient = useQueryClient();\n"
            "  return useMutation({\n"
            f"    mutationFn: {fn},\n"
            f"    onSuccess: () => queryClient.invalidateQueries({{ queryKey: {op.keys}.all }}),\n"
            "  });\n}\n"
        )
    body = "\n".join(out)
    imports = (
        'import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";\n'
        "import {\n" + "".join(f"  {op.function},\n" for op in ops) + '} from "./operations";\n'
        "import {\n"
        + "".join(f"  {k},\n" for k in sorted({op.keys for op in ops}))
        + '} from "./query-keys";\n'
        + _type_imports(body, {"TQueryOptions"})
    )
    return "\n".join(['"use client";\n\n' + HEADER, imports, body])


