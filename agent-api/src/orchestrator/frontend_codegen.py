def mock_operations(contract: dict[str, Any]) -> list[dict[str, Any]]:
    """What the generic MSW handlers need per operation (`src/mocks/handlers.ts` reads this)."""
    fixtures = (contract.get("x-bga") or {}).get("fixtures") or {}
    schemas = contract.get("components", {}).get("schemas", {})
    planned = []
    for op in _ops(contract):
        query = {p["name"]: p for p in op.params if p["in"] == "query"}
        sort = (query.get("sort") or {}).get("schema", {}).get("enum") or []
        limit = (query.get("limit") or {}).get("schema", {})
        entity_schema = schemas.get(f"{op.entity}Response") or {}
        pk = (
            "id"
            if "id" in (entity_schema.get("properties") or {})
            else next(iter(entity_schema.get("properties") or {}), "id")
        )
        entry = {
            "operationId": op.id,
            "method": op.method,
            "path": _PATH_PARAM.sub(lambda m: f":{m.group(1)}", op.path),
            "entity": op.entity,
            "action": op.action,
            "primaryKey": pk,
            "status": next((int(s) for s in sorted(op.raw.get("responses") or {}) if s.startswith("2")), 200),
            "filters": [name for name in query if name not in ("limit", "offset", "sort", "q")],
            "sort": sorted({value.lstrip("-") for value in sort}),
            "search": "q" in query,
            "defaultLimit": limit.get("default", 20),
            "maxLimit": limit.get("maximum", 100),
            "hasFixtures": op.entity in fixtures,
        }
        planned.append(entry)
    return planned


