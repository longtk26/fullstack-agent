def _first_text(records: list[dict[str, Any]], fields: list[str], schema_props: dict[str, Any]) -> str | None:
    if not records:
        return None
    candidates = fields or list(records[0])
    for name in candidates:
        value = records[0].get(name)
        prop = schema_props.get(name) or {}
        if prop.get("format") in ("uuid", "date", "date-time"):
            continue
        if isinstance(value, str) and 2 < len(value) <= 80 and not re.match(r"^[0-9a-f-]{36}$", value):
            return value
    return None


def _route_values(route: str, path: str | None) -> dict[str, str]:
    if path is None:
        return {}
    values = {}
    for segment, value in zip(route.strip("/").split("/"), path.strip("/").split("/"), strict=False):
        if segment.startswith("[") and segment.endswith("]"):
            values[segment[1:-1]] = value
    return values


def _sort_key(value: Any) -> tuple[int, Any]:
    if value is None:
        return (1, "")
    return (0, value if isinstance(value, int | float) else str(value))


def _bound_records(records: list[dict[str, Any]], params: dict[str, Any], values: dict[str, str], action: str | None):
    """The records a list/get binding shows first, the way the mock layer would answer it."""
    resolved = {
        name: values.get(value.removeprefix("$route."))
        if isinstance(value, str) and value.startswith("$route.")
        else value
        for name, value in params.items()
    }
    if action == "get":
        key = resolved.get("id")
        return [record for record in records if str(record.get("id")) == str(key)]
    if "q" in resolved:
        return []
    rows = [
        record
        for record in records
        if all(
            str(record.get(name)) == str(value)
            for name, value in resolved.items()
            if name not in ("limit", "offset", "sort")
        )
    ]
    sort = resolved.get("sort")
    if isinstance(sort, str) and sort:
        field = sort.lstrip("-")
        if len({type(row.get(field)) for row in rows if row.get(field) is not None}) > 1:
            return []
        rows = sorted(rows, key=lambda row: _sort_key(row.get(field)), reverse=sort.startswith("-"))
    offset = int(resolved.get("offset") or 0)
    limit = resolved.get("limit")
    return rows[offset : offset + int(limit)] if limit else rows[offset:]


def _visible_sections(sections: list[dict[str, Any]]) -> Iterator[dict[str, Any]]:
    """Sections shown when the page loads: a Tabs node shows its first child only (Story 17.1 layout nodes)."""
    for section in sections:
        yield section
        children = section.get("children") or []
        yield from _visible_sections(children[:1] if section["component"] == "Tabs" else children)


def _expected_text(
    plan: dict[str, Any], spec: dict[str, Any], contract: dict[str, Any] | None, page_id: str, path: str | None
) -> str | None:
    """Text a route must show once its data has loaded: from the first record of its first data binding."""
    route = next(r for r in plan["routes"] if r["pageId"] == page_id)
    values = _route_values(route["route"], path)
    content = {item["collection"]: item["records"] for item in spec.get("content", [])}
    fixtures = ((contract or {}).get("x-bga") or {}).get("fixtures") or {}
    schemas = (contract or {}).get("components", {}).get("schemas", {})
    for section in _visible_sections(route["sections"]):
        data = section.get("data") or {}
        if data.get("kind") == "content":
            text = _first_text(content.get(data["collection"], []), data.get("fields") or [], {})
        elif data.get("kind") == "operation" and contract is not None:
            entity = (contract_operations(contract)[data["operationId"]]["operation"].get("x-bga") or {}).get("entity")
            props = (schemas.get(f"{entity}Response") or {}).get("properties") or {}
            records = _bound_records(fixtures.get(entity) or [], data.get("params") or {}, values, data.get("action"))
            text = _first_text(records, data.get("fields") or [], props)
        else:
            continue
        if text:
            return text
    return None


def smoke_spec(plan: dict[str, Any], spec: dict[str, Any], contract: dict[str, Any] | None) -> str:
    routes = []
    for test in plan["tests"]:
        if test["kind"] != "route":
            continue
        route = next(r for r in plan["routes"] if r["pageId"] == test["pageId"])
        entry = {
            "id": test["id"],
            "path": test["path"],
            "title": (route.get("seo") or {}).get("title") or route["title"],
        }
        text = _expected_text(plan, spec, contract, test["pageId"], test["path"])
        if text:
            entry["text"] = text
        if test.get("skip"):
            entry["skip"] = test["skip"]
        routes.append(entry)
    return (
        HEADER
        + 'import { expect, test } from "@playwright/test";\n\n'
        + "type TRouteCase = { id: string; path: string | null; title: string; text?: string; skip?: string };\n\n"
        + f"const routes: TRouteCase[] = {json.dumps(routes, indent=2, ensure_ascii=False)};\n\n"
        + "for (const route of routes) {\n"
        + '  test(`${route.id} renders ${route.path ?? ""}`, async ({ page }) => {\n'
        + '    test.skip(Boolean(route.skip) || route.path === null, route.skip ?? "");\n'
        + "    const errors: string[] = [];\n"
        + '    page.on("pageerror", (error) => errors.push(error.message));\n'
        + '    page.on("console", (message) => {\n'
        + '      if (message.type() === "error") errors.push(message.text());\n'
        + "    });\n"
        + "    const response = await page.goto(route.path as string);\n"
        + "    expect(response?.status() ?? 200).toBeLessThan(400);\n"
        + '    await expect(page).toHaveTitle(new RegExp(route.title.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\\\$&")));\n'
        + '    await expect(page.locator("main").first()).toBeVisible();\n'
        + "    if (route.text) await expect(page.getByText(route.text).first()).toBeVisible();\n"
        + '    await page.waitForLoadState("networkidle");\n'
        + "    expect(errors).toEqual([]);\n"
        + "  });\n"
        + "}\n"
    )


def forms_spec(plan: dict[str, Any]) -> str | None:
    cases = []
    by_id = {form["id"]: form for form in plan["forms"]}
    for test in plan["tests"]:
        if test["kind"] != "form":
            continue
        form = by_id[test["formId"]]
        fields = []
        skip = test.get("skip")
        for field in form["fields"]:
            if field.get("hidden") or field.get("value") is not None and str(field.get("value")).startswith("$"):
                continue
            if field.get("type") == "enum":
                if field.get("required"):
                    skip = skip or "required select fields are not filled automatically"
                continue
            if not field.get("required"):
                continue
            fields.append(
                {
                    "label": field.get("label") or field["name"],
                    "kind": "check" if field.get("type") == "boolean" else "fill",
                    "value": str(sample_value(field)),
                }
            )
        case = {
            "id": test["id"],
            "path": test["path"],
            "submit": form.get("submitLabel") or "Submit",
            "fields": fields,
            "toast": (form.get("onSuccess") or {}).get("toast"),
            "navigate": (form.get("onSuccess") or {}).get("navigate"),
        }
        if skip:
            case["skip"] = skip
        cases.append(case)
    if not cases:
        return None
    return (
        HEADER
        + 'import { expect, test } from "@playwright/test";\n\n'
        + "type TFormCase = {\n  id: string;\n  path: string | null;\n  submit: string;\n"
        + '  fields: { label: string; kind: "fill" | "check"; value: string }[];\n'
        + "  toast: string | null;\n  navigate: string | null;\n  skip?: string;\n};\n\n"
        + f"const forms: TFormCase[] = {json.dumps(cases, indent=2, ensure_ascii=False)};\n\n"
        + "for (const form of forms) {\n"
        + "  test(`${form.id} submits`, async ({ page }) => {\n"
        + '    test.skip(Boolean(form.skip) || form.path === null, form.skip ?? "");\n'
        + "    await page.goto(form.path as string);\n"
        + "    for (const field of form.fields) {\n"
        + "      const input = page.getByLabel(field.label, { exact: false }).first();\n"
        + '      if (field.kind === "check") await input.check();\n'
        + "      else await input.fill(field.value);\n"
        + "    }\n"
        + '    await page.getByRole("button", { name: form.submit }).click();\n'
        + "    if (form.toast) await expect(page.getByText(form.toast).first()).toBeVisible();\n"
        + "    else if (form.navigate) await expect(page).toHaveURL(new RegExp(form.navigate));\n"
        + "  });\n"
        + "}\n"
    )


def forms_unit_test(plan: dict[str, Any]) -> str:
    cases = []
    for form in plan["forms"]:
        values = {field["name"]: sample_value(field) for field in form["fields"]}
        for field in form["fields"]:
            if isinstance(field.get("value"), str) and field["value"].startswith("$"):
                values[field["name"]] = "8d2e7a40-1f3b-4c55-8e6a-2b9f4c3d0001"
            if field.get("type") == "date" and values[field["name"]] == "2026-01-15":
                pass
        cases.append((form["schema"], values))
    imports = "".join(f"  {schema},\n" for schema, _ in cases)
    body = "".join(
        f'  it("{schema} accepts valid values", () => {{\n'
        f"    expect({schema}.safeParse({_ts_literal(values)}).success).toBe(true);\n  }});\n"
        for schema, values in cases
    )
    return (
        HEADER
        + 'import { describe, expect, it } from "vitest";\n'
        + (f'import {{\n{imports}}} from "@/lib/forms";\n' if cases else "")
        + '\ndescribe("form schemas", () => {\n'
        + (body or '  it("has no forms", () => {\n    expect(true).toBe(true);\n  });\n')
        + "});\n"
    )


def api_unit_test(contract: dict[str, Any]) -> str:
    ops = [op for op in _ops(contract) if op.method == "GET" and op.action == "list" and not op.path_params]
    fixtures = (contract.get("x-bga") or {}).get("fixtures") or {}
    checks = "".join(
        f'  it("{op.function} answers from the mock layer", async () => {{\n'
        f"    const page = await {op.function}();\n"
        f"    expect(page.total).toBe({len(fixtures.get(op.entity) or [])});\n  }});\n"
        for op in ops
    )
    imports = "".join(f"  {op.function},\n" for op in ops)
    return (
        HEADER
        + 'import { afterAll, afterEach, beforeAll, describe, expect, it } from "vitest";\n'
        + 'import { setApiBase } from "@/lib/api/client";\n'
        + (f'import {{\n{imports}}} from "@/lib/api/operations";\n' if ops else "")
        + 'import { resetMockStore } from "@/mocks/handlers";\n'
        + 'import { server } from "@/mocks/server";\n\n'
        + 'beforeAll(() => {\n  setApiBase("http://localhost/mock-api");\n'
        + '  server.listen({ onUnhandledRequest: "error" });\n});\n'
        + "afterEach(() => {\n  server.resetHandlers();\n  resetMockStore();\n});\n"
        + "afterAll(() => server.close());\n\n"
        + 'describe("generated API client on mocks", () => {\n'
        + (checks or '  it("has no list operations", () => {\n    expect(true).toBe(true);\n  });\n')
        + "});\n"
    )


