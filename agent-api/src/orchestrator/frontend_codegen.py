def _zod(field: dict[str, Any], contract_field: dict[str, Any] | None) -> str:
    kind = field.get("type", "string")
    required = field.get("required", False)
    values = field.get("values") or [v for v in (contract_field or {}).get("enum") or [] if v is not None]
    if kind == "enum" and values:
        expr = f"z.enum({_json(values)})"
    elif kind in ("integer", "number", "decimal"):
        expr = "z.number()" + (".int()" if kind == "integer" else "")
        low = field.get("min") if field.get("min") is not None else (contract_field or {}).get("minimum")
        high = field.get("max") if field.get("max") is not None else (contract_field or {}).get("maximum")
        expr += f".min({_num(low)})" if low is not None else ""
        expr += f".max({_num(high)})" if high is not None else ""
    elif kind == "boolean":
        expr = "z.boolean()"
    elif kind == "email":
        expr = 'z.email("Enter a valid e-mail address")'
    elif kind == "url":
        expr = 'z.url("Enter a valid URL")'
    else:
        expr = "z.string()"
        if required:
            expr += '.min(1, "Required")'
        max_length = field.get("maxLength") or (contract_field or {}).get("maxLength")
        if max_length:
            expr += f".max({max_length})"
    if not required and kind != "boolean":
        expr += ".optional()"
    return expr


def _num(value: Any) -> str:
    return str(int(value)) if float(value).is_integer() else str(value)


def _default(field: dict[str, Any]) -> Any:
    value = field.get("value")
    if isinstance(value, str) and value.startswith("$"):
        return ""  # filled from the route at runtime
    if value is not None:
        return value
    kind = field.get("type", "string")
    if kind == "boolean":
        return False
    if kind in ("integer", "number", "decimal"):
        return None
    if kind == "enum":
        return field["values"][0] if field.get("required") and field.get("values") else None
    return ""


def sample_value(field: dict[str, Any], index: int = 0) -> Any:
    """A valid example for a form field (unit tests and the Playwright form test)."""
    if field.get("value") is not None and not (isinstance(field["value"], str) and field["value"].startswith("$")):
        return field["value"]
    kind = field.get("type", "string")
    if kind == "enum":
        return (field.get("values") or [""])[0]
    if kind in ("integer", "number", "decimal"):
        low = field.get("min")
        return int(low) if low is not None else 1
    if kind == "boolean":
        return True
    if kind == "email":
        return "sam@example.com"
    if kind == "url":
        return "https://example.com"
    if kind == "date":
        return "2026-01-15"
    if kind == "datetime":
        return "2026-01-15T10:00"
    if kind == "tel":
        return "+44 20 7946 0000"
    text = f"Example {field.get('label') or field['name']}"
    return text[: field["maxLength"]] if field.get("maxLength") else text


def forms_ts(plan: dict[str, Any], contract: dict[str, Any] | None) -> str:
    operations = contract_operations(contract) if contract else {}
    if not plan["forms"]:
        return HEADER + "\n// The FrontendSpec has no forms.\nexport {};\n"
    out = [HEADER, 'import { z } from "zod";\n']
    for form in plan["forms"]:
        request_props: dict[str, Any] = {}
        if form.get("operationId") in operations:
            body = (operations[form["operationId"]]["operation"].get("requestBody") or {}).get("content", {})
            schema = resolve(contract, (body.get("application/json") or {}).get("schema", {}))
            request_props = schema.get("properties") or {}
        lines = []
        for field in form["fields"]:
            contract_field = resolve(contract, request_props[field["name"]]) if field["name"] in request_props else None
            lines.append(f"  {_prop(field['name'])}: {_zod(field, contract_field)},")
        defaults = {field["name"]: _default(field) for field in form["fields"]}
        defaults = {name: value for name, value in defaults.items() if value is not None}
        out.append(
            f"/** Form `{form['id']}`"
            + (f" → `{form['operationId']}`" if form.get("operationId") else " (no backend: shows its toast)")
            + " */\n"
            f"export const {form['schema']} = z.object({{\n" + "\n".join(lines) + "\n});\n\n"
            f"export type {form['valuesType']} = z.infer<typeof {form['schema']}>;\n\n"
            f"export const {to_camel(form['id'])}Defaults: Partial<{form['valuesType']}> = {_ts_literal(defaults)};\n"
        )
    return "\n".join(out)


def _ts_literal(value: Any) -> str:
    if isinstance(value, dict):
        if not value:
            return "{}"
        return "{ " + ", ".join(f"{_prop(k)}: {_ts_literal(v)}" for k, v in value.items()) + " }"
    return _json(value)


