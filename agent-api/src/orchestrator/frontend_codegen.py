def _first_text(records: list[dict[str, Any]], fields: list[str], schema_props: dict[str, Any]) -> str | None:
    if not records:
        return None
    candidates = fields or list(records[0])
    for name in candidates:
        value = records[0].get(name)
        prop = schema_props.get(name) or {}
        if prop.get("format") in ("uuid", "date", "date-time"):
            continue
        if isinstance(value, str) and 2 < len(value) <= 80 and not re.match(r"^[0-9a-f-]{36}$", value):
            return value
    return None


def _route_values(route: str, path: str | None) -> dict[str, str]:
    if path is None:
        return {}
    values = {}
    for segment, value in zip(route.strip("/").split("/"), path.strip("/").split("/"), strict=False):
        if segment.startswith("[") and segment.endswith("]"):
            values[segment[1:-1]] = value
    return values


def _sort_key(value: Any) -> tuple[int, Any]:
    if value is None:
        return (1, "")
    return (0, value if isinstance(value, int | float) else str(value))


def _bound_records(records: list[dict[str, Any]], params: dict[str, Any], values: dict[str, str], action: str | None):
    """The records a list/get binding shows first, the way the mock layer would answer it."""
    resolved = {
        name: values.get(value.removeprefix("$route."))
        if isinstance(value, str) and value.startswith("$route.")
        else value
        for name, value in params.items()
    }
    if action == "get":
        key = resolved.get("id")
        return [record for record in records if str(record.get("id")) == str(key)]
    if "q" in resolved:
        return []
    rows = [
        record
        for record in records
        if all(
            str(record.get(name)) == str(value)
            for name, value in resolved.items()
            if name not in ("limit", "offset", "sort")
        )
    ]
    sort = resolved.get("sort")
    if isinstance(sort, str) and sort:
        field = sort.lstrip("-")
        if len({type(row.get(field)) for row in rows if row.get(field) is not None}) > 1:
            return []
        rows = sorted(rows, key=lambda row: _sort_key(row.get(field)), reverse=sort.startswith("-"))
    offset = int(resolved.get("offset") or 0)
    limit = resolved.get("limit")
    return rows[offset : offset + int(limit)] if limit else rows[offset:]


def _visible_sections(sections: list[dict[str, Any]]) -> Iterator[dict[str, Any]]:
    """Sections shown when the page loads: a Tabs node shows its first child only (Story 17.1 layout nodes)."""
    for section in sections:
        yield section
        children = section.get("children") or []
        yield from _visible_sections(children[:1] if section["component"] == "Tabs" else children)


def _expected_text(
    plan: dict[str, Any], spec: dict[str, Any], contract: dict[str, Any] | None, page_id: str, path: str | None
) -> str | None:
    """Text a route must show once its data has loaded: from the first record of its first data binding."""
    route = next(r for r in plan["routes"] if r["pageId"] == page_id)
    values = _route_values(route["route"], path)
    content = {item["collection"]: item["records"] for item in spec.get("content", [])}
    fixtures = ((contract or {}).get("x-bga") or {}).get("fixtures") or {}
    schemas = (contract or {}).get("components", {}).get("schemas", {})
    for section in _visible_sections(route["sections"]):
        data = section.get("data") or {}
        if data.get("kind") == "content":
            text = _first_text(content.get(data["collection"], []), data.get("fields") or [], {})
        elif data.get("kind") == "operation" and contract is not None:
            entity = (contract_operations(contract)[data["operationId"]]["operation"].get("x-bga") or {}).get("entity")
            props = (schemas.get(f"{entity}Response") or {}).get("properties") or {}
            records = _bound_records(fixtures.get(entity) or [], data.get("params") or {}, values, data.get("action"))
            text = _first_text(records, data.get("fields") or [], props)
        else:
            continue
        if text:
            return text
    return None


